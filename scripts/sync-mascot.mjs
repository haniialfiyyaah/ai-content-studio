// Copies the mascot component (source: packages/mascot/src/index.tsx) into the
// renderer, which is built on its own (not part of the pnpm workspace).
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../packages/mascot/src/index.tsx", import.meta.url), "utf8");
writeFileSync(
  new URL("../apps/renderer/src/remotion/mascot.tsx", import.meta.url),
  `// GENERATED by scripts/sync-mascot.mjs — edit packages/mascot/src/index.tsx instead.\n${src}`,
);
console.log("synced mascot → apps/renderer/src/remotion/mascot.tsx");
